def interpret_match_environment(fixture, factors):
    """Interpret supported forecasts without adjusting the match estimates."""
    sport = fixture.get("sport")
    if sport not in {"축구", "야구"} or fixture.get("status") == "cancelled" or fixture.get("voided"):
        return None
    weather = [factor for factor in factors or ()
               if factor.get("category") in {"weather", "venue"} and known_source(factor)]
    if any((factor.get("visual") or {}).get("condition") in {"indoor", "roof"} for factor in weather):
        return None

    notes = FOOTBALL if sport == "축구" else BASEBALL
    for factor in weather:
        if factor["category"] != "weather":
            continue
        visual = factor.get("visual") or {}
        tag = factor.get("forecastTag")
        condition = visual.get("condition")
        if {tag, condition} == {"wind", "rain"}:
            condition = "wind_rain"
        elif (tag == "fog" or condition == "fog") and visual.get("label") == "안개 · 영하권":
            condition = "fog_frost"
        elif tag in notes:
            condition = tag
        if condition in notes:
            headline, explanation, watch = notes[condition]
            return {"headline": headline, "explanation": explanation, "watch": watch}
    return None
